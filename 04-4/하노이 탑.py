def 하노이탑(원판개수, 시작기둥, 대상기둥, 보조기둥):
    if 원판개수 == 1:
        print(시작기둥, "->", 대상기둥)
        return

    # 가장 큰 원판을 옮길 수 있도록 작은 원판들을 보조 기둥으로 옮깁니다.
    하노이탑(원판개수 - 1, 시작기둥, 보조기둥, 대상기둥)

    # 가장 큰 원판을 시작 기둥에서 대상 기둥으로 옮깁니다.
    print(시작기둥, "->", 대상기둥)

    # 보조 기둥에 둔 작은 원판들을 대상 기둥으로 옮깁니다.
    하노이탑(원판개수 - 1, 보조기둥, 대상기둥, 시작기둥)


원판개수 = int(input("원판의 개수를 입력하세요: "))
if 원판개수 < 1:
    raise ValueError("원판 개수는 1 이상이어야 합니다.")

하노이탑(원판개수, "A", "B", "C")